def generate_bulk_rows(count: int, *, key_offset: int = 0) -> List[Row]:
    """生成 count 条新记录，book_key 形如 TP311.SEED.00042，避免与手工键冲突。"""
    out: List[Row] = []
    for k in range(count):
        i = key_offset + k + 1
        subj = _SUBJECTS[k % len(_SUBJECTS)]
        cls = _CLASS_MARKS[k % len(_CLASS_MARKS)]
        book_key = f"{cls}.SEED.{i:05d}"
        lib_book = f"{subj}（教学参考第{(k // 40) + 1}辑）"
        pos = f"{_ZONES[k % len(_ZONES)]}-{(k % 89) + 1:02d}架"
        # 约每 6 本有一本在「已借出」状态，便于演示归还
        is_borrow = 1 if (i % 6 == 0) else 0
        out.append((book_key, lib_book, pos, is_borrow))
    return out


